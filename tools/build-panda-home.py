def mat(name,color,rough=.85,emission=0,texture=None):
 # Textured palette colors are picked display/sRGB swatches. Convert their
 # chosen darker appearance into a true linear albedo first; constants below
 # are already linear. Blender's packed 8-bit sRGB images then need encoding.
 if texture:color=tuple(c/12.92 if c<=.04045 else ((c+.055)/1.055)**2.4 for c in color)
 m=bpy.data.materials.new(name);m.use_nodes=True;m.diffuse_color=(*color,1)
 s=next((n for n in m.node_tree.nodes if n.type=='BSDF_PRINCIPLED'),None)
 if s is None:s=m.node_tree.nodes.new('ShaderNodeBsdfPrincipled')
 out=next((n for n in m.node_tree.nodes if n.type=='OUTPUT_MATERIAL'),None)
 if out is None:out=m.node_tree.nodes.new('ShaderNodeOutputMaterial')
 m.node_tree.links.new(s.outputs['BSDF'],out.inputs['Surface'])
 s.inputs['Base Color'].default_value=(*color,1);s.inputs['Roughness'].default_value=rough
 if emission:s.inputs['Emission Color'].default_value=(*color,1);s.inputs['Emission Strength'].default_value=emission
 if texture:
  n=512;yy,xx=np.mgrid[0:n,0:n]/n;field=np.zeros((n,n));rand=np.random.default_rng(912+len(bpy.data.materials))
  for grid,w in [(3,.55),(11,.28),(43,.13),(127,.04)]:
   a=rand.random((grid+1,grid+1));a[-1,:]=a[0,:];a[:,-1]=a[:,0];gx=xx*grid;gy=yy*grid;i=gx.astype(int);j=gy.astype(int);u=gx-i;v=gy-j;u=u*u*(3-2*u);v=v*v*(3-2*v)
   field+=w*((1-v)*((1-u)*a[j,i]+u*a[j,i+1])+v*((1-u)*a[j+1,i]+u*a[j+1,i+1]))
  if texture=='wood':field=.50+.17*np.sin(xx*TAU*16+np.sin(yy*TAU*2)*.8+field*8)+.13*field
  if texture=='weave':field=.5+.1*np.sin(xx*TAU*64)+.1*np.sin(yy*TAU*64)+field*.06
  pixels=np.ones((n,n,4),dtype=np.float32)
  for c,base in enumerate(color):pixels[:,:,c]=base*(.83+.34*field)
  # Confirmed by 3-swatch emission + GLB roundtrip calibration: linear .25
  # constant matches encoded .5371 image pixels, not raw .25 image pixels.
  pixels[:,:,:3]=np.where(pixels[:,:,:3]<.0031308,pixels[:,:,:3]*12.92,1.055*np.power(pixels[:,:,:3],1/2.4)-.055)
  im=bpy.data.images.new(name+' packed albedo',n,n);im.pixels.foreach_set(pixels.ravel());im.pack()
  node=m.node_tree.nodes.new('ShaderNodeTexImage');node.image=im;m.node_tree.links.new(node.outputs['Color'],s.inputs['Base Color'])
 return m
