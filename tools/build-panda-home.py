def clip(poly,nx,ny,dist):
 out=[]
 for a,b in zip(poly,poly[1:]+poly[:1]):
  fa=a[0]*nx+a[1]*ny-dist;fb=b[0]*nx+b[1]*ny-dist
  if fa<=0:out.append(a)
  if (fa<0)!=(fb<0):t=fa/(fa-fb);out.append((a[0]+t*(b[0]-a[0]),a[1]+t*(b[1]-a[1])))
 return out
